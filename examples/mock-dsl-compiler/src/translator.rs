//! Translates the mock DSL into HCL: each entry is a module of the component its
//! type names, and each output an output block.

use std::path::PathBuf;

use yaml_dsl_compiler::output::{
    Attribute, Block, BodyItem, Expression, FunctionCall, OutputFile, TemplatePart, Traversal,
};
use yaml_dsl_compiler::resolved::{self, Reference, Target, Value, ValueKind};
use yaml_dsl_compiler::{Diagnostic, ResolvedUnit, TargetLanguage, Translator};

use crate::CodeGeneration;

const VERSION_KEY: &str = "version";
const LOCALS_KEY: &str = "locals";
const OUTPUTS_KEY: &str = "outputs";
const MODULE_OUTPUT_NAME: &str = "o";

pub struct MockTranslator {
    code_generation: CodeGeneration,
    config_root: PathBuf,
}

impl MockTranslator {
    pub fn new(code_generation: CodeGeneration, config_root: PathBuf) -> Self {
        Self {
            code_generation,
            config_root,
        }
    }
}

impl Translator for MockTranslator {
    fn translate(&self, unit: &ResolvedUnit) -> Result<Vec<OutputFile>, Vec<Diagnostic>> {
        let mut diagnostics = Vec::new();
        let document = &unit.document;
        let version = match document.get(VERSION_KEY).map(|value| value.local_value()) {
            Some(Value {
                kind: ValueKind::String(version),
                ..
            }) => version.clone(),
            _ => {
                return Err(vec![Diagnostic::at(
                    &document.position,
                    "the document states no `version`",
                )]);
            }
        };
        let mut body = Vec::new();
        for entry in document.entries().unwrap_or_default() {
            match entry.key.as_str() {
                VERSION_KEY | LOCALS_KEY => {}
                OUTPUTS_KEY => {
                    for output in entry.value.entries().unwrap_or_default() {
                        let value = expression(&output.value, &mut diagnostics);
                        let block = Block::new(
                            "output",
                            vec![output.key.clone()],
                            vec![attribute("value", value)],
                        );
                        body.push(BodyItem::Block(block));
                    }
                }
                entry_type => {
                    for declared in entry.value.entries().unwrap_or_default() {
                        let name = entry_name(&declared.key);
                        let mut config =
                            vec![("name".to_owned(), Expression::String(name.to_owned()))];
                        for field in declared.value.entries().unwrap_or_default() {
                            config.push((
                                field.key.clone(),
                                expression(&field.value, &mut diagnostics),
                            ));
                        }
                        let source =
                            format!("{}//{entry_type}", self.code_generation.module_source);
                        let module = Block::new(
                            "module",
                            vec![module_name(entry_type, name)],
                            vec![
                                attribute("source", Expression::String(source)),
                                attribute("version", Expression::String(version.clone())),
                                attribute("config", Expression::Map(config)),
                            ],
                        );
                        body.push(BodyItem::Block(module));
                    }
                }
            }
        }
        if !diagnostics.is_empty() {
            return Err(diagnostics);
        }
        let document_path = unit
            .unit
            .file
            .strip_prefix(&self.config_root)
            .unwrap_or(&unit.unit.file);
        let comment = format!(
            "Generated by mock-dsl-compiler from {}. Do not edit.",
            document_path.display()
        );
        Ok(vec![OutputFile {
            path: self.code_generation.output_file.clone(),
            language: TargetLanguage::Hcl,
            comment: Some(comment),
            body,
        }])
    }
}

fn attribute(name: &str, value: Expression) -> BodyItem {
    BodyItem::Attribute(Attribute::new(name, value))
}

/// The name a key such as `name mock-orders` gives its entry.
fn entry_name(key: &str) -> &str {
    key.rsplit(' ').next().unwrap_or(key)
}

fn module_name(entry_type: &str, name: &str) -> String {
    format!("{entry_type}_{}", name.replace('-', "_"))
}

fn expression(value: &Value, diagnostics: &mut Vec<Diagnostic>) -> Expression {
    match &value.kind {
        ValueKind::Null => Expression::Null,
        ValueKind::Bool(flag) => Expression::Bool(*flag),
        ValueKind::Number(text) => Expression::Number(text.clone()),
        ValueKind::String(text) => Expression::String(text.clone()),
        ValueKind::List(items) => Expression::List(
            items
                .iter()
                .map(|item| expression(item, diagnostics))
                .collect(),
        ),
        ValueKind::Map(entries) => Expression::Map(
            entries
                .iter()
                .map(|entry| (entry.key.clone(), expression(&entry.value, diagnostics)))
                .collect(),
        ),
        ValueKind::Reference(reference) => reference_expression(reference, value, diagnostics),
        ValueKind::Call(call) => Expression::Call(FunctionCall {
            function: call.function.clone(),
            arguments: call
                .arguments
                .iter()
                .map(|argument| expression(argument, diagnostics))
                .collect(),
            expand_final_argument: call.expand_final_argument,
        }),
        ValueKind::Template(parts) => Expression::Template(
            parts
                .iter()
                .map(|part| match part {
                    resolved::TemplatePart::Text(text) => TemplatePart::Text(text.clone()),
                    resolved::TemplatePart::Reference(reference) => TemplatePart::Interpolation(
                        reference_expression(reference, value, diagnostics),
                    ),
                })
                .collect(),
        ),
    }
}

/// A local is written as its value; a reference to an entry reads the module the
/// entry compiles to.
fn reference_expression(
    reference: &Reference,
    value: &Value,
    diagnostics: &mut Vec<Diagnostic>,
) -> Expression {
    match (&reference.target, &reference.scope_key) {
        (Target::Local(local), _) => expression(local, diagnostics),
        (Target::Declaration { .. }, Some(entry_type)) => {
            let module = module_name(entry_type, &reference.name);
            let fields = reference.path.split('.').filter(|field| !field.is_empty());
            Expression::Traversal(Traversal::of_names(
                "module",
                [module.as_str(), MODULE_OUTPUT_NAME]
                    .into_iter()
                    .chain(fields),
            ))
        }
        _ => {
            diagnostics.push(Diagnostic::at(
                &value.position,
                format!("`{}` has no value in HCL", reference.text),
            ));
            Expression::Null
        }
    }
}
